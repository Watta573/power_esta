export type Translations = typeof translations.fr;
type AnyTranslations = typeof translations.fr | typeof translations.en;

interface I18nState {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: AnyTranslations;
}

export const useI18nStore = create<I18nState>()(
  persist(
    (set) => ({
      locale: "fr",
      t: translations.fr,
      setLocale: (locale) => set({ locale, t: translations[locale] }),
    }),
    {
      name: "i18n-storage",
      version: 3,
      migrate: () => ({ locale: "fr", t: translations.fr }),
    },
  ),
);

export function useT() {
  return useI18nStore((s) => s.t);
}
